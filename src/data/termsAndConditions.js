// Substitutes business details into the template. Any field left blank in
// Business Settings falls back to its original [INSERT ...] placeholder,
// so a document generated before legal details are filled in is visibly,
// obviously incomplete — never silently wrong.
export function renderTermsAndConditions(businessDetails = {}) {
  const d = businessDetails || {};
  const fallback = (value, placeholder) => (value && value.trim() ? value.trim() : placeholder);

  return TERMS_AND_CONDITIONS_TEMPLATE
    .replace(/{{LEGAL_NAME}}/g, fallback(d.legalName, "[INSERT FULL LEGAL NAME]"))
    .replace(/{{BUSINESS_STRUCTURE}}/g, fallback(d.businessStructure, "[Limited company, partnership or sole trader]"))
    .replace(/{{COMPANY_NUMBER}}/g, fallback(d.companyNumber, "[INSERT IF APPLICABLE]"))
    .replace(/{{REGISTERED_OFFICE}}/g, fallback(d.registeredOffice, "[INSERT REGISTERED OFFICE IF APPLICABLE]"))
    .replace(/{{PRINCIPAL_ADDRESS}}/g, fallback(d.principalAddress, "[INSERT BUSINESS ADDRESS]"))
    .replace(/{{CONTACT_EMAIL}}/g, fallback(d.contactEmail, "kistconsultinguk@gmail.com"))
    .replace(/{{WEBSITE}}/g, fallback(d.website, "kistconsulting.co.uk"))
    .replace(/{{LIABILITY_CAP}}/g, fallback(d.liabilityCap, "[INSERT LIABILITY CAP]"));
}

// Used to warn before issuing a quote if legal details are still missing —
// checking for the required, meaningfully-legal fields only (not every
// field has to be filled for a quote to be issuable; company number, for
// instance, is genuinely optional for a sole trader).
export function getMissingRequiredBusinessDetails(businessDetails = {}) {
  const d = businessDetails || {};
  const required = [
    ["legalName", "Full legal name"],
    ["businessStructure", "Business structure"],
    ["principalAddress", "Principal business address"],
    ["liabilityCap", "Liability cap"]
  ];
  return required.filter(([key]) => !d[key] || !d[key].trim()).map(([, label]) => label);
}
